# flake8: noqa: E501  -- spec file contents are reproduced verbatim
from __future__ import annotations

from pathlib import Path

from openruyi_precommit_hooks.check_spdx_header import main

GOOD_HEADER_WITH_CONTRIBUTOR = '''\
# SPDX-FileCopyrightText: (C) 2026 Institute of Software, Chinese Academy of Sciences (ISCAS)
# SPDX-FileCopyrightText: (C) 2026 openRuyi Project Contributors
# SPDX-FileContributor: Your Name <your.email@example.com>
#
# SPDX-License-Identifier: MulanPSL-2.0

Name:           foo
Version:        1.0
'''

GOOD_HEADER_WITHOUT_CONTRIBUTOR = '''\
# SPDX-FileCopyrightText: (C) 2025, 2026 Institute of Software, Chinese Academy of Sciences (ISCAS)
# SPDX-FileCopyrightText: (C) 2025, 2026 openRuyi Project Contributors
#
# SPDX-License-Identifier: MulanPSL-2.0

Name:           foo
'''

GOOD_HEADER_YEAR_RANGE = '''\
# SPDX-FileCopyrightText: (C) 2025-2026 Institute of Software, Chinese Academy of Sciences (ISCAS)
# SPDX-FileCopyrightText: (C) 2025-2026 openRuyi Project Contributors
#
# SPDX-License-Identifier: MulanPSL-2.0

Name:           foo
'''


def _write(tmp_path: Path, name: str, content: str) -> str:
    p = tmp_path / name
    p.write_text(content, encoding='utf-8')
    return str(p)


def test_ok_header_with_contributor(tmp_path: Path) -> None:
    retv = main([_write(tmp_path, 'good1.spec', GOOD_HEADER_WITH_CONTRIBUTOR)])
    assert retv == 0


def test_ok_header_without_contributor(tmp_path: Path) -> None:
    retv = main([_write(tmp_path, 'good2.spec', GOOD_HEADER_WITHOUT_CONTRIBUTOR)])
    assert retv == 0


def test_ok_header_year_range(tmp_path: Path) -> None:
    retv = main([_write(tmp_path, 'good3.spec', GOOD_HEADER_YEAR_RANGE)])
    assert retv == 0


