def test_plain_comment_before_spdx_block(tmp_path: Path) -> None:
    # The SPDX block must be present at the start of the file, but other
    # leading comments are harmless as long as the block itself is there.
    content = '''\
# generated by openruyi-tooling
# SPDX-FileCopyrightText: (C) 2026 Institute of Software, Chinese Academy of Sciences (ISCAS)
# SPDX-FileCopyrightText: (C) 2026 openRuyi Project Contributors
#
# SPDX-License-Identifier: MulanPSL-2.0

Name:           foo
'''
    retv = main([_write(tmp_path, 'ok3.spec', content)])
    assert retv == 0


def test_multiple_files_all_bad(tmp_path: Path) -> None:
    retv = main([
        _write(tmp_path, 'x1.spec', 'Name: a\n'),
        _write(tmp_path, 'x2.spec', 'Name: b\n'),
    ])
    assert retv == 1
